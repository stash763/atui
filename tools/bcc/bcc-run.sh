#!/bin/bash
# bcc-run.sh -- drive Borland C++ 5.02 under wine against this tree.
#
#   tools/bcc/bcc-run.sh compile src/tui/theme.cpp      # one file, shows output
#   tools/bcc/bcc-run.sh sweep                            # everything, table + message counts
#   tools/bcc/bcc-run.sh probe t_stdmap.cpp               # one file, compiler+linker, run it
#
# Why wine rather than the Windows box: bcc32 through the remote shell costs
# seconds per file and every measurement is a round trip; here the compiler is
# a local process and its headers are grep-able files.  Wine runs the *compiler*
# faithfully -- what it does NOT stand in for is a Windows 98/NT4/2000 console,
# so anything about behaviour still gets checked on real systems.
#
# Objects go to $OUT with `-o<file>`: bc5 has no object *directory* switch (the
# `-o<dir>` form is accepted and ignored -- measured: with -oZ:\out\ the object
# does not appear there), and the working directory of a compile is spoken for,
# because bc5 searches it for a quoted include and nothing else (see below).
# Hence `-o$OUT/<name>.obj` per file, which also keeps tvision's app.cpp and
# src/tui/app.cpp from both wanting to be app.obj, and keeps the tree clean.
set -u

PREFIX=${BCC_WINEPREFIX:-$HOME/.local/share/wineprefixes/Win32}
export WINEPREFIX="$PREFIX"
export WINEDEBUG=${WINEDEBUG:--all}
BCC32=${BCC32:-'C:\BC5\BIN\bcc32.exe'}
# Where the installation keeps its headers, in Windows form: what a
# compat header needs to include the real <fstream.h>.
BCC_INCLUDE_WIN=${BCC_INCLUDE_WIN:-'C:\BC5\INCLUDE'}

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT=${BCC_OUT:-/tmp/bccobj}
mkdir -p "$OUT"

# Z: is wine's view of the unix root, so the tree needs no copying.
wpath() { echo "Z:\\${1#/}" | sed 's#/#\\#g'; }

# compat/bcc/include goes first: it owns header names this installation does
# not have (<cstdio>, <mutex>) and replaces the two it has but which declare
# nothing (<cstring>).  The generated root header (below) is what lets
# compat's <fstream> reach the installation's own.
# src/net and src/tui are the only two source directories on -I, and that list
# is not a matter of taste.  A compile runs from the .cpp's own directory, which
# covers an unprefixed include of a sibling; what it does not cover is a header
# in another directory doing one -- net/chat_request.h includes "oai_body.h", and
# compiling src/main.cpp from src/ cannot see it.  Those two are the whole set
# (measured over the include graph: they are the only directories whose headers
# are reached from a .cpp elsewhere and whose headers name a sibling).  The
# others stay off because -I answers angle includes too: put src/core on it and
# src/core/string.h BECOMES <string> for the whole build, which is 63 files of
# "'string' is not a member of 'std'".  Anything added here has to be checked
# against the installation's header names for the same reason.
INC="-I$(wpath "$ROOT/compat/bcc/include") -I$(wpath "$ROOT/src") -I$(wpath "$ROOT/src/net") -I$(wpath "$ROOT/src/tui") -I$(wpath "$ROOT/tvision/include") -I$(wpath "$ROOT/tvision/include/tvision")"
# bc5 searches neither the directory of the file being compiled nor the directory
# of the header that is doing the including -- only the working directory and -I
# (measured both ways: "journal.h" beside journal.cpp is "Unable to open include
# file" with the cwd elsewhere, and dirB/sib.h included from dirB/h.h is not
# found with the cwd in dirA).  Every unprefixed quoted include in src/ names a
# sibling or one of the two directories above, so a compile runs from the source
# file's own directory.

# One generated file, one line, because the quoting of an absolute include path
# does not survive a bc5 response file (measured) and this is the only way to
# give compat/bcc/include/fstream.h the path it needs.
mkdir -p "$OUT/gen"
cat > "$OUT/gen/atui_bcc_root.h" <<ROOT
/* generated by tools/bcc/bcc-run.sh -- the installation's own headers, by path */
#ifndef ATUI_BCC_ROOT_H
#define ATUI_BCC_ROOT_H
#define ATUI_BCC_INCLUDE_FSTREAM "$BCC_INCLUDE_WIN\\fstream.h"
#define ATUI_BCC_INCLUDE_IOSTREAM "$BCC_INCLUDE_WIN\\iostream.h"
#endif
ROOT
INC="$INC -I$(wpath "$OUT/gen")"
DEF="-D__WIN32__ -DWIN32 -D_CONSOLE -DNOTASM -DATUI_VERSION=\"0.0.0-bcc\""
NET=${BCC_NET:-1}
[ "$NET" = 1 ] && DEF="$DEF -DATUI_HAVE_NETWORK=1"
COPTS="-3 -Od -w- $INC $DEF ${BCC_FLAGS:-}"
FLAGS="-c $COPTS"

# Wine prints one line about Z: having no volume serial on every start; it is
# noise from the mapping, not from the compiler, and the toolchain is fine.
noise() { grep -v 'Read access denied for device' ; }

# compile_one <abs-source> <object-name>; compiles from the source file's own
# directory (bc5's only search path for an unprefixed quoted include besides -I
# is the working directory), writes the object to $OUT, leaves the output in
# $OUT/cur.log, prints it, and returns the compiler's own status (a pipeline
# would replace it with grep's, which is how a first version of this reported
# clean builds).
compile_one() {
    local dir name
    dir=$(dirname "$1"); name=$(basename "$1")
    ( cd "$dir" && wine "$BCC32" $FLAGS "-o$(wpath "$OUT/$2")" "$name" > "$OUT/cur.log" 2>&1 )
    local rc=$?
    # The positive check is the object.  A compiler that was never found -- wrong
    # WINEPREFIX, and the default ~/.wine has no Borland in it -- prints no Error
    # line, and "no Error line" is exactly what a clean compile looks like from
    # here.  No object with no error is not a clean compile, it did not happen.
    if [ "$rc" = 0 ] && [ ! -f "$OUT/$2" ]; then
        echo "bcc-run: no object produced: $BCC32 did not run (prefix $PREFIX?)" >&2
        rc=72
    fi
    noise < "$OUT/cur.log"
    return $rc
}

case "${1:-}" in
  compile)
    shift
    src=$1
    [ -f "$ROOT/$src" ] || { echo "not in tree: $src"; exit 2; }
    compile_one "$ROOT/$src" o.obj
    ;;
  probe)
    # compile, link and run one self-contained probe from /tmp.  COPTS, not
    # FLAGS: -c would stop before the link, and a probe that never linked is
    # how one round of this "measured" things that had never been built.
    shift
    f=$1
    base=$(basename "$f" .cpp)
    ( cd "$OUT" && wine "$BCC32" -e"$base.exe" $COPTS "$(wpath "$f")" > cur.log 2>&1 ); rc=$?
    noise < "$OUT/cur.log"
    if [ "$rc" = 0 ] && [ -f "$OUT/$base.exe" ]; then
        ( cd "$OUT" && wine "$base.exe" 2>&1 )
    fi
    exit $rc
    ;;
  sweep)
    # source/platform is not swept, because it is not built: that tree is the
    # C++14 terminal layer, and an era compiler does not compile it and does not
    # need it -- the classic layer carries its own complete console driver for
    # Borland in hardwrvr.cpp, which is why this target exists at all.  Measured:
    # hardwrvr.cpp compiles clean; win32con.cpp, the modern one, does not get
    # compiled on any target older than a C++14 standard library.
    files=$(cd "$ROOT" && ls src/*.cpp src/core/*.cpp src/tui/*.cpp src/net/*.cpp src/tools/*.cpp src/settings/*.cpp src/platform/*.cpp 2>/dev/null)
    tv=$(cd "$ROOT" && ls tvision/source/tvision/*.cpp 2>/dev/null | grep -v geninc.cpp)
    echo "=== sweeping $(echo "$files $tv" | wc -w) files with $(basename "$BCC32") under wine ==="
    : > "$OUT/results.txt"
    : > "$OUT/todo"
    for f in $tv;   do echo "tv  $f" >> "$OUT/todo"; done
    for f in $files; do echo "at  $f" >> "$OUT/todo"; done
    n=0; ok=0
    while read -r grp rel; do
      n=$((n+1))
      obj="${grp}_$(basename "$(dirname "$rel")")_$(basename "$rel" .cpp).obj"
      ( cd "$ROOT/$(dirname "$rel")" && wine "$BCC32" $FLAGS \
            "-o$(wpath "$OUT/$obj")" "$(basename "$rel")" > "$OUT/raw_$obj.log" 2>&1 )
      rc=$?
      noise < "$OUT/raw_$obj.log" > "$OUT/log_$obj.txt"
      # bc5 writes "Error <file> <line>: ..." with no leading space; a pattern
      # that expects one counts zero and every file looks clean.
      errs=$(grep -cE '^ ?(Error|Fatal) ' "$OUT/log_$obj.txt")
      # The object is the evidence; the exit code alone would call a compiler that
      # never started a clean compile, and sweep results are what claims about this
      # target are made from.
      st=OK
      if [ "$rc" != 0 ]; then
          st=FAIL
      elif [ ! -f "$OUT/$obj" ]; then
          st=NOOBJ
          echo "bcc-run: no object for $rel: the compiler did not run (prefix $PREFIX?)" >&2
      fi
      if [ "$st" = OK ]; then ok=$((ok+1)); fi
      echo "$st $grp $rel $errs" >> "$OUT/results.txt"
      [ $((n % 20)) = 0 ] && echo "  .. $n done ($ok clean)"
    done < "$OUT/todo"
    echo
    echo "=== $ok of $n compile clean ==="
    for g in tv tp at; do
      printf '%s: %s clean of %s\n' "$g" "$(awk -v g=$g '$2==g && $1=="OK"' "$OUT/results.txt" | wc -l)" "$(awk -v g=$g '$2==g' "$OUT/results.txt" | wc -l)"
    done
    echo
    echo '=== the compiler messages, most frequent first ==='
    # lines look like "Error Z:\home\...\theme.cpp 8: Unable to open include
    # file 'cstddef.h'"; the interesting part is after the line number.
    for f in "$OUT"/log_*.txt; do grep -hE '^ ?(Error|Fatal) ' "$f"; done |
      sed -E 's/^ ?(Error|Fatal) [^ ]+ [0-9]+: //; s/ in function .*$//; s/in function .*$//' |
      sort | uniq -c | sort -rn | head -25
    ;;
  *)
    sed -n '3,12p' "$0"
    ;;
esac
